import 'package:drift/drift.dart';

/// Категории выводов AI.
enum LessonCategory {
  planning,      // Паттерны планирования (когда и сколько)
  estimates,     // Оценки времени (занижение/завышение)
  preferences,   // Предпочтения пользователя
  productivity,  // Паттерны продуктивности (дни, часы)
}

/// Выводы AI, полученные из анализа истории работы.
///
/// Это слой «обучения» агента. AI не дообучается, но:
///   1. Пишет выводы в эту таблицу, когда видит статистически
///      значимый паттерн (например «оценки кода занижены в 1.8x»).
///   2. Читает эту таблицу при составлении плана дня.
///   3. Выводы хранятся вместе с confidence и evidence_count,
///      чтобы можно было доверять только проверенным выводам.
///
/// Примеры выводов:
///   - «По пятницам выполнение плана ~40% — не перегружать»
///   - «Оценки кода систематически занижены в ~1.8x»
///   - «После 20:00 производительность падает»
///   - «Задачи с дедлайном через 3+ дня часто откладываются»
///
/// Пользователь в любой момент может посмотреть таблицу и понять,
/// «чему научился AI», а также удалить/исправить неверные выводы.
class AiLessons extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Категория вывода (см. LessonCategory).
  TextColumn get category => textEnum<LessonCategory>()();

  /// Текстовое описание вывода (читаемое для человека).
  TextColumn get lesson => text()();

  /// Числовое выражение вывода (опционально).
  /// Например: для вывода «оценки занижены в 1.8x» здесь будет 1.8.
  /// AI использует его при умножении estimated_minutes на коэффициент.
  RealColumn get numericValue => real().nullable()();

  /// Степень уверенности (0.0 .. 1.0).
  /// Чем больше evidence_count, тем выше confidence.
  /// Диапазон валидируется в DAO.
  RealColumn get confidence =>
      real().withDefault(const Constant(0.5))();

  /// Количество наблюдений, на которых основан вывод.
  /// Чем больше — тем вывод надёжнее.
  IntColumn get evidenceCount =>
      integer().withDefault(const Constant(1))();

  /// Когда вывод был впервые сделан.
  DateTimeColumn get createdAt =>
      dateTime().withDefault(currentDateAndTime)();

  /// Когда вывод был обновлён (новое наблюдение подтвердило или уточнило).
  DateTimeColumn get updatedAt =>
      dateTime().withDefault(currentDateAndTime)();
}
