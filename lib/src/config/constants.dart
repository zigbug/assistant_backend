import 'dart:io';

/// Конфигурационные константы приложения.
///
/// Чувствительные значения (API-ключ) читаются из переменных окружения,
/// что позволяет использовать разные значения в dev и prod.
///
/// Приоритет: переменная окружения > дефолтное значение для dev.
/// В продакшене (Docker) значения задаются через docker-compose env.
class AppConstants {
  /// Версия API, используемая в маршрутах (например, /api/v1/...).
  /// Версионирование нужно для совместимости с клиентами при изменениях.
  static const String apiVersion = 'v1';

  /// Ключ API для аутентификации запросов к бэкенду.
  ///
  /// Читается из переменной окружения `API_KEY`. В dev-режиме используется
  /// плейсхолдер — его НЕЛЬЗЯ использовать в продакшене.
  ///
  /// Требования к prod-значению: минимум 32 символа, случайная строка.
  /// Генерация: `openssl rand -hex 32`
  static String get apiKey =>
      Platform.environment['API_KEY'] ?? 'dev-key-change-me-in-production';

  /// Порт, на котором будет запущен HTTP-сервер.
  ///
  /// Читается из `PORT` (стандарт для контейнеров). Дефолт 8081 для локальной
  /// разработки — порт 8080 часто занят (MTAgentService, прокси, Docker).
  static int get serverPort =>
      int.tryParse(Platform.environment['PORT'] ?? '') ?? 8081;

  /// Хост, на котором слушает сервер.
  ///
  /// `0.0.0.0` — слушать на всех интерфейсах (нужно в Docker и при доступе
  /// извне через reverse proxy). Для изолированного локального запуска
  /// можно установить `localhost`.
  static String get serverHost =>
      Platform.environment['HOST'] ?? '0.0.0.0';
}
